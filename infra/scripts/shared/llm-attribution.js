'use strict';

// Model attribution filter for generated commit messages and PR descriptions (AGENTS.md「GitHub 与安全」): commits
// and PRs carry no Claude Code, ChatGPT/Codex or other LLM signature. Only whole signature lines are removed —
// "Generated with/by <model>" markers and Co-authored-by trailers naming a model account — so human co-authors and
// ordinary text that merely mentions a model stay intact.

// Optional Markdown bullet before the signature, as produced when a commit body is turned into PR summary bullets.
const BULLET_PREFIX = /^\s*(?:[-*]\s+)?/u;

// "🤖 Generated with [Claude Code](…)", "Generated by Codex", "Generated with ChatGPT" and similar markers.
const GENERATED_LINE = /^(?:🤖\s*)?Generated\s+(?:with|by)\s+\[?(?:Claude(?:\s+Code)?|ChatGPT|(?:OpenAI\s+)?Codex|GPT[-\w.]*|Gemini|(?:GitHub\s+)?Copilot|Cursor)\b/iu;

const CO_AUTHOR_LINE = /^Co-authored-by:\s*(.*?)\s*(?:<([^>]*)>)?\s*$/iu;

// Co-author names that identify a model account. Claude must be followed by a product or model word (or stand alone)
// so a human co-author such as "Claude Dupont" is kept.
const MODEL_AUTHOR = /^(?:Claude(?:\s+(?:Code|Opus|Sonnet|Haiku|Fable)\b.*)?|ChatGPT\b.*|(?:OpenAI\s+)?Codex\b.*|GPT-[\w.-]+|Gemini(?:\s+(?:CLI|Code\s+Assist|[\d.]+\b.*))?|(?:GitHub\s+)?Copilot\b.*|Cursor(?:\s+Agent)?)$/iu;

// Vendor no-reply addresses used by model co-author trailers.
const MODEL_EMAIL = /^noreply@(?:anthropic|openai)\.com$/iu;

function isLlmAttributionLine(line) {
  const text = String(line || '').replace(BULLET_PREFIX, '').trim();
  if (!text) return false;
  if (GENERATED_LINE.test(text)) return true;
  const coAuthor = CO_AUTHOR_LINE.exec(text);
  if (!coAuthor) return false;
  return MODEL_AUTHOR.test(coAuthor[1]) || MODEL_EMAIL.test((coAuthor[2] || '').trim());
}

/**
 * Removes model attribution lines from a commit message or PR body. Text without such lines is returned unchanged;
 * otherwise blank lines left doubled by a removal collapse to one and trailing blank lines are trimmed, keeping the
 * original final newline.
 */
function stripLlmAttribution(text) {
  const source = String(text || '');
  const lines = source.split('\n');
  if (!lines.some(isLlmAttributionLine)) return source;

  const kept = [];
  let removedSinceKept = false;
  for (const line of lines) {
    if (isLlmAttributionLine(line)) {
      removedSinceKept = true;
      continue;
    }
    const previousBlank = kept.length > 0 && !kept[kept.length - 1].trim();
    if (removedSinceKept && previousBlank && !line.trim()) continue;
    removedSinceKept = false;
    kept.push(line);
  }
  const body = kept.join('\n').replace(/\s+$/u, '');
  return source.endsWith('\n') ? `${body}\n` : body;
}

module.exports = {
  isLlmAttributionLine,
  stripLlmAttribution,
};
