'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');

const { isLlmAttributionLine, stripLlmAttribution } = require('../llm-attribution');

test('Claude Code generated markers and co-author trailers are attribution lines', () => {
  for (const line of [
    '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    'Generated with Claude Code',
    'Co-Authored-By: Claude <noreply@anthropic.com>',
    'Co-authored-by: Claude Opus 4.7 <noreply@anthropic.com>',
    '- Co-Authored-By: Claude Code <noreply@anthropic.com>',
    '* 🤖 Generated with [Claude Code](https://claude.com/claude-code)',
  ]) {
    assert.equal(isLlmAttributionLine(line), true, line);
  }
});

test('ChatGPT, Codex and other model signatures are attribution lines', () => {
  for (const line of [
    'Generated with ChatGPT',
    'Generated by Codex',
    'Generated with [Codex](https://chatgpt.com/codex)',
    'Co-authored-by: ChatGPT <noreply@openai.com>',
    'Co-authored-by: Codex <codex@openai.com>',
    'Co-authored-by: OpenAI Codex <noreply@openai.com>',
    'Co-authored-by: Gemini <gemini@example.com>',
    'Co-authored-by: Copilot <copilot@github.com>',
  ]) {
    assert.equal(isLlmAttributionLine(line), true, line);
  }
});

test('human co-authors and ordinary lines mentioning models are kept', () => {
  for (const line of [
    'Co-authored-by: Alice <alice@example.com>',
    '- 支持 Claude Code attribution 配置',
    '- remote merges pass commit title',
    'Generated with care by the team',
    '### 概要',
    '',
  ]) {
    assert.equal(isLlmAttributionLine(line), false, line);
  }
});

test('stripLlmAttribution removes only attribution lines and collapses trailing blanks', () => {
  const body = [
    '### 概要',
    '- real point',
    '- Co-Authored-By: Claude <noreply@anthropic.com>',
    '',
    '### 语义审查',
    '- 支持 ChatGPT 署名过滤',
    '',
    'Co-authored-by: Alice <alice@example.com>',
    '',
    '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    'Co-authored-by: Codex <codex@openai.com>',
    '',
  ].join('\n');
  assert.equal(stripLlmAttribution(body), [
    '### 概要',
    '- real point',
    '',
    '### 语义审查',
    '- 支持 ChatGPT 署名过滤',
    '',
    'Co-authored-by: Alice <alice@example.com>',
    '',
  ].join('\n'));
});

test('stripLlmAttribution leaves text without attribution byte-identical', () => {
  const body = '### 概要\n- keep\n\n### Review Gate\n- Gate-Result: skipped\n';
  assert.equal(stripLlmAttribution(body), body);
  assert.equal(stripLlmAttribution(''), '');
});
